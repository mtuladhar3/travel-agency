export function getRegionPackages(region, packagesByRegion = {}) {
  return (
    region.packages ??
    packagesByRegion[region.href] ??
    (region.popularPackage ? [region.popularPackage] : [])
  );
}

export function buildRegionPackageSlides(regions, packagesByRegion = {}) {
  return regions.flatMap((region) => {
    const packages =
      region.packages ??
      packagesByRegion[region.href] ??
      (region.popularPackage ? [region.popularPackage] : []);

    return packages.map((pkg, index) => ({
      id: `${region.href}-${index}`,
      pkg,
      regionHref: region.href,
      regionLabel: region.label,
    }));
  });
}

export function getRegionStartIndices(slides) {
  const indices = {};

  slides.forEach((slide, index) => {
    if (indices[slide.regionHref] === undefined) {
      indices[slide.regionHref] = index;
    }
  });

  return indices;
}
